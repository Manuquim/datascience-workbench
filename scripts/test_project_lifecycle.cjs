const fs=require('node:fs');
const path=require('node:path');
const {spawn}=require('node:child_process');
const {createRequire}=require('node:module');
const {chromium}=createRequire(path.resolve(__dirname,'../frontend/package.json'))('playwright');
(async()=>{
 const root=path.resolve(__dirname,'..');
 const data=fs.mkdtempSync(path.join(root,'.qa-lifecycle-'));
 const code="import sys;sys.path.insert(0,'backend');from pathlib import Path;from app.main import create_app;from app.config import Settings;import uvicorn;app=create_app(Settings(data_dir=Path(sys.argv[1])));server=uvicorn.Server(uvicorn.Config(app,host='127.0.0.1',port=5173));app.state.shutdown_callback=lambda:None;server.run()";
 const server=spawn(path.join(root,'.venv/Scripts/python.exe'),['-c',code,data],{cwd:root,windowsHide:true,stdio:'ignore'});
 let browser;
 try{
  let ready=false;
  for(let i=0;i<100;i++){try{if((await fetch('http://127.0.0.1:5173/api/health')).ok){ready=true;break;}}catch{} await new Promise(r=>setTimeout(r,100));}
  if(!ready)throw Error('Test server did not start');
  browser=await chromium.launch({headless:true,channel:'msedge'});
  const page=await browser.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:5173');
  await page.getByRole('button',{name:'Cerrar programa',exact:true}).waitFor();
  await page.getByRole('button',{name:'+ Nuevo proyecto',exact:true}).click();
  await page.getByLabel('Nombre del proyecto').fill('Lifecycle QA');
  await page.getByRole('button',{name:'Crear proyecto',exact:true}).click();
  await page.getByRole('button',{name:'Cerrar proyecto',exact:true}).waitFor();
  if(await page.getByRole('button',{name:'Cerrar programa',exact:true}).count())throw Error('Shutdown available with open project');
  await page.locator('input[type=file]').setInputFiles(path.join(root,'examples/ventas.csv'));
  await page.getByRole('heading',{name:'Vista previa',exact:true}).waitFor({timeout:30000});
  await page.getByRole('button',{name:'Pipeline',exact:true}).click();
  await page.getByText('Editar el plan completo',{exact:false}).click();
  const draft='{"name":"Pending draft","steps":[],"charts":[],"questions":[],"explanation":"saved"}';
  await page.getByLabel('Plan JSON').fill(draft);
  await page.getByRole('button',{name:'Asistente IA',exact:true}).click();
  await page.getByLabel('Instrucci\u00f3n para la IA').fill('Pending instruction');
  await page.getByRole('button',{name:'Cerrar asistente',exact:true}).click();
  await page.getByRole('button',{name:'Cerrar proyecto',exact:true}).click();
  await page.getByRole('button',{name:'Cerrar programa',exact:true}).waitFor();
  await page.getByRole('heading',{name:'Tu laboratorio de datos.',exact:true}).waitFor();
  if(await page.getByRole('button',{name:'Crear mi primer proyecto',exact:true}).count())throw Error('First-project welcome shown for an existing project');
  await page.getByText('1 tabla',{exact:true}).waitFor();
  await page.screenshot({path:path.join(data,'home-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2))throw Error('Home mobile overflow');
  await page.screenshot({path:path.join(data,'home-mobile.png'),fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.reload();
  await page.getByRole('button',{name:'Abrir proyecto Lifecycle QA',exact:true}).click();
  await page.getByText('Editar el plan completo',{exact:false}).click();
  await page.getByLabel('Plan JSON').waitFor();
  if(await page.getByLabel('Plan JSON').inputValue()!==draft)throw Error('Draft was not restored');
  await page.getByRole('button',{name:'Asistente IA',exact:true}).click();
  if(await page.getByLabel('Instrucci\u00f3n para la IA').inputValue()!=='Pending instruction')throw Error('Instruction was not restored');
  await page.getByRole('button',{name:'Cerrar asistente',exact:true}).click();
  await page.getByRole('button',{name:'Cerrar proyecto',exact:true}).click();
  await page.getByRole('button',{name:'Cerrar programa',exact:true}).click();
  await page.getByRole('heading',{name:'Programa cerrado',exact:true}).waitFor();
  await page.reload();
  await page.getByRole('button',{name:'Reiniciar programa',exact:true}).click();
  await page.getByRole('button',{name:'Cerrar programa',exact:true}).waitFor();
  await page.getByRole('button',{name:'Abrir proyecto Lifecycle QA',exact:true}).waitFor();
  if(errors.length)throw Error(errors.join('\n'));
  console.log('Home cards, metadata summary, mobile layout, restore and program restart passed. QA: '+data);
 }finally{if(browser)await browser.close();server.kill();}
})().catch(e=>{console.error(e);process.exitCode=1;});
